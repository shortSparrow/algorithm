/**
 * Вибір за лінійний час очікування
 * Уявімо, що у вас є велика коробка з іграшками різних розмірів.
 * Ваше завдання — знайти іграшку, яка, наприклад, є третьою за величиною.
 * Це і є задача вибору: знайти i-й найменший елемент у масиві.
 *
 * Здавалося б, найпростіший спосіб — це відсортувати всі іграшки за розміром,
 * а потім просто взяти третю. Це спрацює, але сортування може зайняти багато часу,
 * особливо якщо розмір масиву дуже великий. Наприклад, швидке сортування (quicksort)
 * має очікуваний час O(n * log n).
 *
 * Тут на допомогу приходить алгоритм RANDOMIZED-SELECT.
 * Він працює за принципом "розділяй і володарюй", але з однією ключовою відмінністю:
 * замість того, щоб обробляти обидві частини масиву (як це робить швидке сортування),
 * він працює лише з однією з них.
 *
 * Очікуваний час роботи такого алгоритму O(n)
 *
 *
 *
 *
 *
 * Тут показано приклад пошуку n-го найменшого елементу
 *
 * Як це працює?
 * Хочу знайти третій найменший елемент
 * 1) Вибір опорного елемента: Алгоритм випадковим чином вибирає один елемент з
 *    масиву (назвемо його опорним).
 *
 * 2) Розбиття масиву: Далі ви розділяєте всі інші числа на дві групи: ті, що менші
 *    за вибране, і ті, що більші за нього.
 *
 * 3) Визначення, де шукати: Після цього ви дивитеся, в якій групі знаходиться ваше третє найменше число.
 *    Якщо ви знайшли, що вибране число — це саме третє за величиною, то все, ви його знайшли!
 *    Якщо ж воно, наприклад, більша за третє, то ви знаєте, що ваше число знаходиться в
 *    групі "менших". І навпаки.
 *
 * 4) Рекурсивний виклик: Тепер вам не потрібно дивитися на всі числа. Ви просто повторюєте
 *    процес (рекурсивно) тільки в тій групі, де, як ви знаєте, знаходиться шукане число.
 *
 *
 * Опис алгоритму
 * Нехай є масив [3,6,8,2,1,4,5] і ми шукаємо друге найменше число
 *  randomizedSelect([3,6,8,2,1,4,5], 0, 6, 2);
 *     randomizedPartition([3,6,8,2,1,4,5], 0, 6);
 *       Нехай опорний елемент 4 (обираємо від індексу 0 до індексу 6)
 *       [3,6,8,2,1,5,4] міняємо місцями останній елемент і опорний
 *             |
 *       [3,2,8,6,1,5,4] міняємо місцями 6 і 2
 *             |
 *       [3,2,1,6,8,5,4] міняємо місцями 8 і 1
 *             |
 *       [3,2,1,4,8,5,6] міняємо місцями опорний елемент (4) і останній
 *                       swap-нутий елемент (8 - це індекс 4) - 1 (індекс 3 - це 6).
 *       return 3 (Повертаємо індекс опорного елементу)
 *
 *     q=3
 *     k=3-0+1=4
 *     i=2
 *     randomizedSelect([3,2,1,4,8,5,6], 0, 3-1, 2);
 *       randomizedPartition([3,2,1,4,8,5,6], 0, 2, 2)
 *         Нехай опорний елемент 1 (індекс 2) (обираємо від індексу 0 до індексу 2)
 *         [3,2,1,  4,8,5,6] міняємо місцями останній елемент і опорний (Вони однакові - НІЧОГО НЕ ЗМІНИЛОСЯ)
 *                 |
 *         [1,2,3,  4,8,5,6] міняємо місцями опорний елемент (1) і останній
 *                           swap-нутий елемент (таких немає, тому це початкове значення left-1=2-1=1) - 1 (індекс 0 - це 1).
 *                           Отже нічого не міняється
 *         return 0 (Повертаємо індекс опорного елементу)
 *
 *       q=0
 *       k=0-0+1=1
 *       i=2
 *       randomizedSelect([1,2,3,4,8,5,6], 0 + 1, 2, 2 - 1);
 *         randomizedPartition([1,2,3,4,8,5,6], 1, 2)
 *         Нехай опорний елемент 3 (індекс 2) (обираємо від індексу 0 до індексу 2)
 *         [1,3,2,  4,8,5,6] міняємо місцями останній елемент і опорний (Вони однакові - НІЧОГО НЕ ЗМІНИЛОСЯ)
 *                 |
 *         [1,2,3,  4,8,5,6] міняємо місцями 1 і 3 [1,2,3,  4,8,5,6] міняємо місцями опорний елемент (2) і
 *                           останній swap-нутий елемент - 1 (2) - НІЧОГО НЕ ЗМІНЮЄТЬСЯ
 *         return 2
 *
 *         q=2
 *         k=2-1+1=2
 *         i=2
 *         return arr[q] (це 2)
 *
 *         randomizedSelect([1,2,3,4,8,5,6], 1, 2 - 1, i);
 *           left==right
 *           return arr[right] (return arr[1] -> 2)
 *
 * Відповідь: Другий найменший елемент 2
 *
 *
 * Найгірший час роботи randomizedSelect O(n^2) бо алгоритм може виконуватися надзвичайно
 * невдало - завжди розбивати навколо найбільшого елемента з тих, що лишилися, а розбиття
 * триває час O(n).
 *  Приклад: [3,2,9,0,7,5,4,8,6,1]
 *  Pivot буде обиратися у зворотньому порядку, спочатку 9, потім 8, потім 7 ...
 * Але очікуваний час роботи буде O(n), якщо всі елементи різні
 * Також можливий ітеративний варіант алгоритму, де повністю виключена рекурсія
 * 
 * 
 * Можливий варіант для найгіршого випадку опрацювати його за O(n)
 * Для цього потрібно змінити функцію randomizedSelect на детермінований select.
 * Дивитися determinedSelect.js
 * 
 */

function randomizedSelect(arr, left, right, i) {
  if (left == right) {
    return arr[right];
  }

  // randomizedPartition - розбиває масив на два підмасиви і повертає індекс опорного елементу після всіх swap
  const q = randomizedPartition(arr, left, right);
  /**
   * k - це ранг опорного елементу, тобто це його індекс + 1.
   * Якщо ранг опорного елементу 4, то це означає що він четвертий найменший елемент
   * А оскільки всі зліва від опорного менші за нього то відповідь у підмасиві
   * з left до опорного включно якщо i < k, а якщо i > k то у правому підмасиві
   */
  const k = q - left + 1;
  if (i == k) {
    return arr[q];
  } else if (i < k) {
    return randomizedSelect(arr, left, q - 1, i);
  } else {
    return randomizedSelect(arr, q + 1, right, i - k);
  }
}

/**
 * Ця функція розбиває масив на два підмасиви
 * Нехай є масив [3,6,8,2,1,4,5]
 * left = 0, right = 6
 * Нехай опорний елемент 4
 * Тепер змінюємо масив так щоб зліва у нас були всі елементи, які менші
 * за опорний елемент, а з права ті що більші
 * [3,6,8,2,1,5,4] міняємо місцями останній елемент і опорний
 *        |
 * [3,2,8,6,1,5,4] міняємо місцями 6 і 2
 *        |
 * [3,2,1,6,8,5,4] міняємо місцями 8 і 1
 *        |
 * [3,2,1,4,8,5,6] міняємо місцями опорний елемент і наступний після останнього меншого ніж опорний (тобто наступний після 1 (а це 6))
 *
 * Тепер нас цікавить тільки ця частина [3,2,1,4]
 * І повертаємо індекс останнього елемента з цього відрізку - тобто 3 індекс
 */
function randomizedPartition(arr, left, right) {
  // Випадково вибираємо індекс
  const randomIndex = Math.floor(Math.random() * (right - left + 1)) + left;
  // Обмінюємо випадковий елемент з останнім елементом масиву
  swap(arr, randomIndex, right);

  const pivot = arr[right];
  let i = left - 1;

  for (let j = left; j < right; j++) {
    if (arr[j] <= pivot) {
      i++;
      // Обмінюємо елементи
      swap(arr, i, j);
    }
  }

  // Обмінюємо елемент на позиції i+1 з опорним елементом
  swap(arr, i + 1, right);

  return i + 1;
}

function swap(arr, i, j) {
  const temp = arr[i];
  arr[i] = arr[j];
  arr[j] = temp;
}


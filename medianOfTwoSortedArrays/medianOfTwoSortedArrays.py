def medianOf2(a, b):
    n = len(a)
    m = len(b)
    i = 0
    j = 0

    m1 = -1
    m2 = -1

    for count in range((m + n) // 2 + 1):
        m2 = m1

        if i != n and j != m:
            if a[i] > b[j]:
                m1 = b[j]
                j += 1
            else:
                m1 = a[i]
                i += 1

        elif i < n:
            m1 = a[i]
            i += 1

        # if only b[] has remaining elements
        else:
            m1 = b[j]
            j += 1

    # return median based on odd/even size
    if (m + n) % 2 == 1:
        return m1
    else:
        return (m1 + m2) / 2.0



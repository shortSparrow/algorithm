# Перевірка чи число просте за допомогою решета Ератосфена.
# 
# Ми додаємо всі числа від 1 до n включно в масив і далі починаємо з числа 2 (бо це найменше просте число, 
# якщо не враховувати 1). Ми видаляємо всі числа які діляться на 2, бо вони точно не прості, 
# якщо діляться на 2. Наступне число яке не було видалено неодмінно просте. У нашому випадку це 3. 
# Потім видаляємо всі числа які діляться на 3. Наступне не видалене число неодмінно просте – це число 5. І так далі.



def eratosthenesTest(n):
    # Створюємо булевий масив, де індекс — це саме число
    is_prime = [True] * (n + 1)
    is_prime[0] = is_prime[1] = False  # 0 і 1 не є простими

    factor = 2
    while factor * factor <= n:
        # Якщо число ще не викреслене, воно просте
        if is_prime[factor]:
            # Починаємо викреслювати з квадрата числа з кроком factor
            for i in range(factor * factor, n + 1, factor):
                is_prime[i] = False
        factor += 1

    # Повертаємо список усіх індексів, які залишилися True
    return [num for num, prime in enumerate(is_prime) if prime]

print(eratosthenesTest(1))



# Розкладання натурального числа на прості множники.
# 
# Цей алгоритм дечим схожий на решето Ератосфена.
# Ми беремо перше просте число 2 і дивимося чи наше n ділиться на нього. Якщо так то 2 є одним з простих множників,
# ми ділимо n на 2 і потім дивимося чи результат ділиться на 2. Якщо ділиться то наше n ділиться на 22 і так 
# до поки наше число не перестане ділитися на 2. Потім ми беремо наступне просте число, ми просто додаємо 
# до 2+1 і отримаємо 3, далі йде перевірка на простоту if(t%n==0) якщо ні то додаємо ще +1 поки не отримаємо 
# просте число і далі перевіряємо чи ділиться наше число яке лишилося після попередніх ділень на на це нове 
# просте число і так далі.

def prime_factors(n, only=False):
    p = {}
    t = 2
    while (n > 1):
        if ((n%t) == 0):
            if (t in p):
                p[t] += 1
            else:
                p[t] = 1
            n = n // t
        else:
            t += 1
    w = []
    for k in sorted(list(p.keys())):
        w.append((k,p[k]))
    if (only):
        w = [i[0] for i in w]
    return w



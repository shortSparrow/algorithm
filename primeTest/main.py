# Пошук того чи число просте є вельми важливою задачею, оскільки у програмуванні
# дуже багато чого зав'язано на простих числах.
# 
# Тут ми розглянемо дві основні проблеми: 
#   1. Перевірка чи число просте 
#   2. Розкладання числа на прості множники. Оскільки згідно основною теореми арифметики 
#      ми можемо розкласти на прості множники будь-яке натуральне число.
# 
# Напевно найстарішим алгоритмом для перевірки числа на простоту є решето Ератосфена, 
# яке працює за O(n log(log(n)), що є непоганим значенням. Його приклад наведено 
# у файлі eratosthenesTest.py.
# Так само розкладання числа на прості множники наведено там же (eratosthenesTest.py)
# 
# Алгоритм Міллер Рабіна та мала теорема Ферма.
# Але решето Ератосфена не найоптимальніший спосіб перевірки чи число просте. Бо нам
# все таки треба пройтися по всім числам від 1 до n. Тому є кращий алгоритм Міллер Рабіна,
# який побудований на основі малої теореми Ферма. Ми маємо два файли, у першому файлі 
# fermatPrimeTest.py ми розглядаємо як мала теорема Ферма може допомогти нам у пошуку 
# простих чисел. Але цей підхід, хоч і дуже простий і чудовий, але має недоліки, 
# а саме псевдопрості числа Кармайкла. І тут нам допомагає алгоритм Міллер Рабіна, бо він
# хоч і так само імовірнісний через малу теорему Ферма, але долає псевдопрості числа Кармайкла
# і має імовірність правильно визначити чи число просте у >75% відсотках. Для реальних чисел 
# із якими ми працюємо в житті (до 2*10^19) від має 100% достовірність при 7 циклах. А для
# більших чисел можна збільшити кількість цикл до 64 і мати неймовірно низьку імовірність помилки. 

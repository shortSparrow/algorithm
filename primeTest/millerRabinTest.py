import random

# Імовірнісний тест на простоту числа Міллер Рабіна.
# 
# Цей тест у своїй основі має малу теорему Ферма, так само як і у fermatPrimeTest.py, логіка така
# сама, але ми також додаємо додаткові захисні механізми, щоб більш достовірно перемірити чи число
# просте чи складене.
# 
# За замовченням ставимо 5 раундів. Потрібну кількість раундів для перевірки числа n наведено нижче у таблиці.
# 
# Розберемо логіку алгоритму.
# Мала теорема Ферма говорить що якщо n–просте, a–ціле, що не ділиться на n тоді: a^n-1 = 1 mod (n)
# І ми можемо це використати у нашій задачі для пошуку простого числа. Бо ця формула гарантовано 
# працює для простих чисел і інколи для деяких складених (в залежності від a). 
# 
# Ми беремо випадкове число а у діапазоні (1;n-1] (так само як і у fermatPrimeTest.зy), але тут не 
# одразу ставимо ставимо його у формулу x=a^d mod n. 
# У нас з'являється додатковий код while (d%2 == 0)
# Він для того щоб не одразу стрибати до степеня n-1 як це робить fermatPrimeTest.py, а розкласти n-1
# на 2^s*d і потім підніматися назад до n-1 шляхом піднесення результату до квадрата 
# (це ми робимо у циклі for j in range(s-1)). Тобто ми робимо цю перевірку для кожного s яке у нас є.
# Це дозволяє нам ніби зазирнути всередину і подивитися чи на якомусь етапі домноження на квадрат 
# не з’являється числа що не відповідає малій теоремі Ферма. Це відсіює складені числа
# які прикидаються простими. І які при використанні степеня n-1 дали б остачу 1, але коли ми 
# поступово піднімаємо степінь то це викаже ці числа, бо для них десь остача буде на 1.
# 
# Якщо залишок від ділення на n буде 1 то мала теорема Ферма виконується
# і число імовірно просте, тож ми одразу йдемо до наступної ітерації, з іншим a.
# 
# Але якщо залишок від ділення не 1
# 


def MillerRabinTest(n, rounds=5):
    #  2 - це єдине парне просте число
    if (n==2):
        return True

    # Якщо ділиться на 2 то точно не просте і одразу відкидаємо це
    if (n%2 == 0): 
        return False

    # n-1 це гарантовано парне число. Тут ми дізнаємося скільки 2 містить наше число n-1 і запишемо це у s
    # Розкладаємо n-1 на 2^s * d
    s = 0
    d = n-1
    while (d%2 == 0):
        s += 1
        d //= 2

    for k in range(rounds):
        a = int(random.randint(1,n-1))
        x = pow(a,d,n)  # це запис для x=a^d mod n. Варто ЗАУВАЖИТИ, що ми у формулу вставляємо не n-1, а саме d.
                        # Ми так пройдемося по кожному d аж поки не дійдемо до n-1

        # Якщо x≡1 mod(n) або x≡1 mod(n-1) то мала теорема Ферма виконується і число може бути простим 
        # і ми переходимо до наступного раудну (бо складене теж може пройти (див. числа Кармайкла)) 
        if (x==1) or (x == n-1):
            continue

        # Якщо x не дорівнює ні 1, ні n-1, ми запускаємо внутрішній цикл s-1 разів і на кожній 
        # ітерації обчислюємо x=x^2 mod(n). Якщо коч один з них дасть x≡1 mod(n-1) то виходимо із внутрішнього 
        # циклу і переходимо до наступного раунду (з тією ж метою що і вище).
        b = False
        for j in range(s-1):
            x = pow(x,2,n) # це запис для x=x^2 mod n
            if (x == n-1):
                b = True
                break
        if (b):
            continue
        return False
    return True



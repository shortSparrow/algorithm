import random

# Тест Ферма на те, чи є число простим є імовірнісним.
# 
# Тут використовується мала теорема Ферма та модульна алгебра. Коротко нагадаємо що це. 
#   1 mod(5)=1 - читається як 1 мод 5. Мається на увазі залишок від ділення 1 на 5. 
#   1 mod(9)=1
#   5 mod(3)=2
# 
#   1 mod (n) завжди = 1
# 
# В оригінальний теоремі Ферма замість = використовується знак із тьома рисками. 
# І говоримо що одне конгруенто іншому. Але я їбу як вставити тут такий знак, тому
# буде знак = (суть все одно така сама).
#  
# Мала теорема Ферма говорить що якщо n–просте, a–ціле, що не ділиться на n тоді: a^n-1 = 1 mod (n)
# І ми можемо це використати у нашій задачі для пошуку простого числа.
# 
# Ми беремо випадковим чином число a у діапазоні (1;n-1] і підставляємо його у формулу. 
# Якщо залишок від ділення = 1 то число імовірно просте.
# 
# Тут важливо розуміти, що мала теорема Ферма працює для всіх простих чисел, але ніде не 
# сказано, що вона не працює для складених чисел. Є складені числа які можуть теж давати 
# залишок від ділення 1, саме тому варто такий тест  провести кілька разів. 
# 
# Також є друга проблема, так звані псевдопрості числа Кармайкла. Це складені числа які мають 
# деякі властивості простих чисел і вони можуть у наші теоремі теж давати залишок від ділення 1.
# Але із ними проблема в тому, що збільшення кількості циклів не сильно допоможе це вирішити,
# все одно буде достатньо серйозна імовірність помилки.
# 
# Значно кращий тест Міллера Рабіна представлено у файлику millerRabinTest.py, хоча він так 
# само в основі своїй використовує малу теорему Ферма, та має кілька захисних механізмів 
# від псевдопростих чисел Кармайкла.

def FermatPrimeTest(n):
    # Якщо n <=1 то це точно не просте число (1 простим не вважаємо)
    if n <=1:
        return False

    # Якщо буде а=1 то 1^n-1 mod 1 завжди буде вірним, тож це число є беззмістовним, тож беремо число від 2
    a = int(random.randint(2,n-1)) 
    x = pow(a,n-1, n)  # це запис для x=a^(n-1) mod n

    # Якщо x=1 то мала теорема Ферма виконується і число може бути простим 
    # і ми переходимо до наступного раунду (бо складене теж може пройти (див. числа Кармайкла)) 
    if (x==1):
      return True

    return False

print(FermatPrimeTest(11)) # True

for i in range(100):
  print(FermatPrimeTest(561)) # 561 - це перше псевдопросте число Кармайкла і буде виводити то False то True